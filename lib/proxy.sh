#!/usr/bin/env bash
# fawwk — the Caddy reverse proxy: routes domains/paths to app containers, handles HTTPS.

proxy_running() { [[ $(docker inspect -f '{{.State.Running}}' "$FAWWK_PROXY" 2>/dev/null) == true ]]; }

# Creates the docker network and the proxy container if they don't exist.
proxy_ensure() {
  docker network inspect "$FAWWK_NETWORK" >/dev/null 2>&1 || docker network create "$FAWWK_NETWORK" >/dev/null
  mkdir -p "$CADDY_DIR/custom"
  [[ -f $CADDY_DIR/Caddyfile ]] || proxy_render >"$CADDY_DIR/Caddyfile"
  if ! docker inspect "$FAWWK_PROXY" >/dev/null 2>&1; then
    docker run -d --name "$FAWWK_PROXY" --network "$FAWWK_NETWORK" --restart unless-stopped \
      -p 80:80 -p 443:443 -p 443:443/udp \
      -v "$CADDY_DIR:/etc/caddy:ro" \
      -v fawwk_caddy_data:/data -v fawwk_caddy_config:/config \
      --log-opt max-size=10m --log-opt max-file=3 \
      "$CADDY_IMAGE" caddy run --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
  elif ! proxy_running; then
    docker start "$FAWWK_PROXY" >/dev/null
  fi
}

# The image the running proxy was created from (e.g. caddy:2 on servers set up before pinning).
proxy_image() { docker inspect -f '{{.Config.Image}}' "$FAWWK_PROXY" 2>/dev/null || true; }

# Recreates the proxy on CADDY_IMAGE. Certificates live in a volume, so they're kept; sites are
# unreachable for the few seconds the new container takes to start.
proxy_upgrade() {
  spin_start "Pulling $CADDY_IMAGE"
  docker pull -q "$CADDY_IMAGE" >/dev/null 2>&1 || { spin_stop; die "Couldn't pull $CADDY_IMAGE"; }
  spin_stop
  docker rm -f "$FAWWK_PROXY" >/dev/null 2>&1 || true
  proxy_ensure
  proxy_reload
}

# Prints the full Caddyfile generated from every app's routes.
# Runs in a subshell so loading apps doesn't clobber the caller's A_* variables.
proxy_render() (
  # shellcheck disable=SC1090
  [[ -f $FAWWK_CONF ]] && source "$FAWWK_CONF"
  local name r host path upstream rows=()
  while IFS= read -r name; do
    [[ -z $name ]] && continue
    app_load "$name"
    [[ -z $A_ROUTES ]] && continue
    upstream=-
    [[ $A_STATE == running && -n $A_CONTAINER ]] && upstream="$A_CONTAINER:$A_PORT"
    for r in $A_ROUTES; do
      host=${r%%/*} path=''
      [[ $r == */* ]] && path="/${r#*/}"
      rows+=("$host|${#path}|$path|$upstream|${A_STRIP:-yes}|$A_NAME")
    done
  done < <(app_names)

  printf '# Generated by fawwk at %s. Do not edit: it is rewritten on every deploy.\n' "$(ts)"
  printf '# Add your own site blocks in %s/custom/*.caddy\n\n' "$CADDY_DIR"
  printf '{\n\temail %s\n}\n\n' "${EMAIL:-admin@localhost}"
  printf 'import /etc/caddy/custom/*.caddy\n\n'

  # Every host answers the check token, so the DNS check can tell whether traffic for a domain
  # really reaches this server, even behind Cloudflare or another proxy (see origin_probe).
  printf '(fawwk_check) {\n\thandle %s {\n\t\trespond "%s" 200\n\t}\n}\n\n' "$CHECK_PATH" "$(check_token)"
  # Plain-HTTP catch-all for hosts without a site of their own (no app yet, the wildcard check).
  # Hosts with a site keep Caddy's automatic redirect to HTTPS, which it places before a catch-all.
  printf 'http:// {\n\timport fawwk_check\n\thandle {\n\t\trespond 404\n\t}\n}\n\n'

  # GitHub webhooks and the one-click GitHub App setup, handled by the fawwk-hooks container.
  # Oversized bodies are cut off here, before they reach it (same limit as MAX_BODY in hooks.py).
  if [[ -n ${PANEL_HOST-} && -f $FAWWK_ETC/hooks.enabled ]]; then
    printf '%s {\n\timport fawwk_check\n\tencode zstd gzip\n\t@hooks path /hooks/* /github/*\n\thandle @hooks {\n\t\trequest_body {\n\t\t\tmax_size 4MiB\n\t\t}\n\t\treverse_proxy fawwk-hooks:8000\n\t}\n\thandle {\n\t\trespond "Fawwk" 404\n\t}\n}\n\n' "$PANEL_HOST"
  fi

  ((${#rows[@]})) || exit 0
  # Group by host; longest path first so /api/v2 wins over /api, and / comes last.
  printf '%s\n' "${rows[@]}" | sort -t'|' -k1,1 -k2,2nr | awk -F'|' '
    function body(up) {
      if (up == "-") print "\t\trespond \"Service unavailable\" 503"
      else print "\t\treverse_proxy " up
    }
    function close_host() {
      if (cur == "") return
      if (!hasroot) print "\thandle {\n\t\trespond \"Not found\" 404\n\t}"
      print "}\n"
    }
    {
      host = $1; path = $3; up = $4; strip = $5; app = $6
      if (host != cur) {
        close_host(); cur = host; hasroot = 0; n = 0
        print host " {"
        print "\timport fawwk_check"
        print "\tencode zstd gzip"
      }
      print "\t# app: " app
      if (path == "") {
        hasroot = 1
        print "\thandle {"
      } else {
        n++
        print "\t@r" n " path " path " " path "/*"
        print "\thandle @r" n " {"
        if (strip == "yes") print "\t\turi strip_prefix " path
      }
      body(up)
      print "\t}"
    }
    END { close_host() }'
)

# Regenerates the Caddyfile, validates it, and reloads Caddy gracefully (no dropped connections).
proxy_reload() {
  local new="$CADDY_DIR/Caddyfile.new" cur="$CADDY_DIR/Caddyfile" vlog="$FAWWK_LOG/caddy-validate.log"
  mkdir -p "$CADDY_DIR/custom" "$FAWWK_LOG"
  proxy_render >"$new"
  proxy_running || proxy_ensure
  if ! docker exec "$FAWWK_PROXY" caddy validate --config /etc/caddy/Caddyfile.new --adapter caddyfile >"$vlog" 2>&1; then
    err "The generated proxy config is invalid, keeping the current one:"
    grep -iE 'error|invalid' "$vlog" | tail -n 5 | ui_quote || true
    rm -f "$new"
    return 1
  fi
  [[ -f $cur ]] && cp -f "$cur" "$cur.bak"
  mv -f "$new" "$cur"
  if ! docker exec "$FAWWK_PROXY" caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >>"$vlog" 2>&1; then
    err "Caddy refused the new config; restoring the previous one."
    [[ -f $cur.bak ]] && mv -f "$cur.bak" "$cur"
    docker exec "$FAWWK_PROXY" caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1 || true
    return 1
  fi
}

# route_owner ROUTE [EXCEPT_APP] — prints the app already using ROUTE, if any.
route_owner() (
  local name r
  while IFS= read -r name; do
    [[ -z $name || $name == "${2-}" ]] && continue
    app_load "$name"
    for r in $A_ROUTES; do [[ $r == "$1" ]] && { printf '%s' "$name"; exit 0; }; done
  done < <(app_names)
  exit 0
)

# Validates a route for an app: syntax, panel reservation, not used by another app.
route_check() {
  local r=$1 app=$2 owner
  valid_route "$r" || return 1
  if [[ -n ${PANEL_HOST-} && ${r%%/*} == "$PANEL_HOST" ]]; then
    warn "$PANEL_HOST is reserved for the Fawwk panel."
    return 1
  fi
  owner=$(route_owner "$r" "$app")
  [[ -z $owner ]] || { warn "$r is already used by app '$owner'."; return 1; }
}

route_url() { printf 'https://%s' "$1"; }
